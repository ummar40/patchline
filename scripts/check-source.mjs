// Repository hygiene gate: authored files must be ASCII, free of banned marketing/filler
// phrases, and free of TODO markers (unfinished work is tracked in docs/implementation-plan.md).
import { readdir, readFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const self = relative(root, fileURLToPath(import.meta.url))
  .split(sep)
  .join("/");

const skippedDirectories = new Set([
  ".git",
  ".next",
  "node_modules",
  "dist",
  "coverage",
  "src/db/generated",
]);
const skippedFiles = new Set(["package-lock.json", "prompt.md", "next-env.d.ts"]);
const binaryExtensions = new Set([".png", ".ico", ".jpg", ".jpeg", ".gif", ".woff", ".woff2"]);

const bannedPhrases = [
  "generated by ai",
  "ai-powered magic",
  "revolutionary ai",
  "intelligent magic",
  "as an ai",
  "placeholder response",
  "simulated result",
  "mock success",
];
const marker = /\b(TODO|FIXME|XXX)\b/;

async function* walk(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolute = join(directory, entry.name);
    const path = relative(root, absolute).split(sep).join("/");
    if (entry.isDirectory()) {
      if (!skippedDirectories.has(path)) {
        yield* walk(absolute);
      }
    } else if (entry.isFile() && !skippedFiles.has(path)) {
      const dot = entry.name.lastIndexOf(".");
      if (dot === -1 || !binaryExtensions.has(entry.name.slice(dot).toLowerCase())) {
        yield { absolute, path };
      }
    }
  }
}

const problems = [];
let scanned = 0;

for await (const file of walk(root)) {
  scanned += 1;
  const lines = (await readFile(file.absolute, "utf8")).split("\n");
  lines.forEach((line, index) => {
    const location = `${file.path}:${index + 1}`;
    const column = line.search(/[^\t\r\x20-\x7e]/);
    if (column !== -1) {
      const code = line.codePointAt(column).toString(16).toUpperCase().padStart(4, "0");
      problems.push(`${location}:${column + 1} non-ASCII character U+${code}`);
    }
    if (file.path === self) {
      return;
    }
    const lowered = line.toLowerCase();
    for (const phrase of bannedPhrases) {
      if (lowered.includes(phrase)) {
        problems.push(`${location} banned phrase "${phrase}"`);
      }
    }
    if (marker.test(line)) {
      problems.push(`${location} unfinished-work marker`);
    }
  });
}

if (problems.length > 0) {
  console.error(problems.join("\n"));
  console.error(`\n${problems.length} problem(s) in ${scanned} files.`);
  process.exit(1);
}
console.log(`Source check passed (${scanned} files).`);
